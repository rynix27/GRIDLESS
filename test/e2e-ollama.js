// End-to-end for the offline-AI path: internet OFF + Ollama ON + question NOT in stored knowledge
// => layer "local-model". Uses a mock Ollama we can stop / restart / break. Run: npm run test:e2e:ollama
const { spawn } = require("child_process");
const http = require("http");
const path = require("path");
const assert = require("assert/strict");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const OLLAMA_PORT = 3195, APP_PORT = 3210;
let mode = "ok"; // ok | missing
function startMock() {
  return new Promise((resolve) => {
    const srv = http.createServer((req, res) => {
      let body = "";
      req.on("data", (c) => (body += c));
      req.on("end", () => {
        res.setHeader("Content-Type", "application/json");
        if (req.url === "/api/tags") return res.end(JSON.stringify({ models: mode === "ok" ? [{ name: "llama3.2:3b" }] : [] }));
        if (req.url === "/api/chat") {
          if (mode === "missing") { res.statusCode = 404; return res.end(JSON.stringify({ error: "model 'llama3.2:3b' not found" })); }
          const p = JSON.parse(body);
          const sys = p.messages[0].content;
          const turns = p.messages.filter((m) => m.role !== "system");
          return res.end(JSON.stringify({ message: { role: "assistant", content: `LLAMA turns=${turns.length} last="${turns[turns.length - 1].content}" ctx=${/Relevant offline reference material/.test(sys)} ownknowledge=${/own general knowledge/.test(sys)}` } }));
        }
        res.statusCode = 404; res.end("{}");
      });
    });
    srv.listen(OLLAMA_PORT, "127.0.0.1", () => resolve(srv));
  });
}

const app = spawn(process.execPath, [path.join(__dirname, "..", "server", "index.js")], {
  env: { ...process.env, PORT: String(APP_PORT), OLLAMA_URL: `http://127.0.0.1:${OLLAMA_PORT}`, CONNECTIVITY_CHECK_URL: "http://127.0.0.1:9", OPENAI_API_KEY: "", NETWORK_KEY: "" },
  stdio: "ignore",
});
const B = `http://127.0.0.1:${APP_PORT}`;
const post = async (msgs, extra = {}) => {
  const r = await fetch(B + "/api/chat", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ messages: msgs, ...extra }) });
  return { status: r.status, json: await r.json() };
};
const health = async () => (await fetch(B + "/api/ollama/health")).json();
const u = (c) => ({ role: "user", content: c });

(async () => {
  let mock = await startMock();
  await sleep(2500);
  let n = 0;
  const check = async (name, fn) => { await fn(); n++; console.log("  ok  -", name); };

  await check("health: Ollama reachable and model installed", async () => {
    const h = await health(); assert.equal(h.ready, true); assert.equal(h.modelInstalled, true);
  });
  await check("DEFINITION OF DONE: unmatched question -> local-model answer generated by Ollama", async () => {
    const r = await post([u("Explain how a CPU works")]);
    assert.equal(r.status, 200); assert.equal(r.json.layer, "local-model"); assert.equal(r.json.model, "llama3.2:3b");
    assert.match(r.json.reply, /^LLAMA/); assert.match(r.json.reply, /ctx=false ownknowledge=true/); assert.equal(r.json.groundedIn, 0);
  });
  await check("code-style question also goes to the model", async () => {
    const r = await post([u("Write a Python program to calculate prime numbers")]);
    assert.equal(r.json.layer, "local-model");
  });
  await check("follow-up: full conversation history reaches the model", async () => {
    const r = await post([u("Explain quantum computing simply"), { role: "assistant", content: "ok..." }, u("make it shorter")]);
    assert.match(r.json.reply, /turns=3 last="make it shorter"/);
  });
  await check("matching stored knowledge is added as CONTEXT, answer still comes from the model", async () => {
    const r = await post([u("how do I purify water by boiling")]);
    assert.equal(r.json.layer, "local-model"); assert.ok(r.json.groundedIn >= 1); assert.match(r.json.reply, /ctx=true/);
  });
  await check("useKnowledge:false disables retrieval (pure model test)", async () => {
    const r = await post([u("how do I purify water by boiling")], { useKnowledge: false });
    assert.equal(r.json.layer, "local-model"); assert.equal(r.json.groundedIn, 0); assert.match(r.json.reply, /ctx=false/);
  });
  await check("offlineOnly flag bypasses cloud/mesh and still answers locally", async () => {
    const r = await post([u("hello there")], { offlineOnly: true });
    assert.equal(r.json.layer, "local-model");
  });
  await check("model not installed -> specific actionable message, honest reference-only labelling", async () => {
    mode = "missing";
    const h = await health(); assert.equal(h.reachable, true); assert.equal(h.modelInstalled, false); assert.match(h.message, /ollama pull llama3.2:3b/);
    const r = await post([u("how do I purify water by boiling")]);
    assert.equal(r.json.layer, "reference-only"); assert.match(r.json.reply, /REFERENCE-ONLY MODE/); assert.match(r.json.reply, /not an AI-generated answer/);
    assert.equal(r.json.localAi.kind, "model-missing");
    const miss = await post([u("zzzz qqqq xxxx")]);
    assert.equal(miss.status, 503); assert.match(miss.json.error, /ollama pull/);
    mode = "ok";
  });
  await check("Ollama stopped -> clearly 'not running' + reference-only mode", async () => {
    await new Promise((r) => mock.close(r)); mock.closeAllConnections && mock.closeAllConnections();
    const h = await health(); assert.equal(h.reachable, false); assert.equal(h.kind, "not-running"); assert.match(h.message, /ollama serve/);
    const r = await post([u("how do I purify water by boiling")]);
    assert.equal(r.json.layer, "reference-only"); assert.equal(r.json.localAi.kind, "not-running"); assert.match(r.json.reply, /REFERENCE-ONLY MODE/);
  });
  await check("Ollama restarted -> AI answers resume", async () => {
    mock = await startMock(); await sleep(300);
    const r = await post([u("Explain how a CPU works")]);
    assert.equal(r.json.layer, "local-model");
  });

  console.log(`\n${n} offline-AI checks passed`);
  app.kill(); mock.close(); process.exit(0);
})().catch((e) => { console.error("FAILED:", e.message); app.kill(); process.exit(1); });
